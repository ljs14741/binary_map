    static String pick(Bucket bucket, String seed) {
        String[] pool = lines(bucket);
        int h = seed.hashCode();
        h ^= (h >>> 16);
        h *= 0x7feb352d;
        h ^= (h >>> 15);
        return pool[Math.floorMod(h, pool.length)];
    }

    static String[] lines(Bucket bucket) {
        return switch (bucket) {
            case GOOD -> GOOD;
            case OK -> OK;
            case BAD -> BAD;
        };
    }
